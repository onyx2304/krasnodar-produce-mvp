-- Run in Supabase SQL Editor. Product prices are stored as integer kopecks.
create extension if not exists pgcrypto;

create table if not exists public.products (
  id text primary key,
  name text not null,
  category text not null check (category in ('fruit','vegetable','greens')),
  price_minor integer not null check (price_minor >= 0),
  unit text not null check (unit in ('kg','bunch')),
  description text not null default '',
  is_active boolean not null default true,
  price_is_estimate boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null,
  customer_note text,
  status text not null default 'new'
    check (status in ('new','confirmed','shopping','ready','courier_assigned','delivered','cancelled')),
  subtotal_minor integer not null check (subtotal_minor >= 0),
  delivery_fee_minor integer check (delivery_fee_minor is null or delivery_fee_minor >= 0),
  total_minor integer check (total_minor is null or total_minor >= 0),
  currency text not null default 'RUB'
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  product_name text not null,
  quantity numeric(8,3) not null check (quantity > 0),
  unit text not null,
  unit_price_minor integer not null check (unit_price_minor >= 0),
  line_total_minor integer not null check (line_total_minor >= 0)
);

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.supplier_prices (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id),
  product_id text not null references public.products(id),
  price_minor integer not null check (price_minor >= 0),
  observed_at timestamptz not null default now(),
  notes text
);

create table if not exists public.deliveries (
  id bigint generated by default as identity primary key,
  order_id uuid not null unique references public.orders(id) on delete cascade,
  courier_name text,
  courier_phone text,
  fee_minor integer check (fee_minor is null or fee_minor >= 0),
  status text not null default 'pending'
    check (status in ('pending','assigned','picked_up','delivered','failed')),
  assigned_at timestamptz,
  delivered_at timestamptz,
  notes text
);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id),
  movement_type text not null check (movement_type in ('purchase','sale','spoilage','adjustment')),
  quantity numeric(8,3) not null,
  unit_cost_minor integer check (unit_cost_minor is null or unit_cost_minor >= 0),
  order_id uuid references public.orders(id),
  notes text,
  created_at timestamptz not null default now()
);

