-- Enable RLS. Public users may read active products only; orders are written only by the server using service-role key.
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.suppliers enable row level security;
alter table public.supplier_prices enable row level security;
alter table public.deliveries enable row level security;
alter table public.stock_movements enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select to anon, authenticated
  using (is_active = true);

-- No public policies for orders, order_items, suppliers, supplier_prices, deliveries, stock_movements.
